-- Audio lantunan Asmaul Husna menjadi DAFTAR (maksimal 10), bukan satu audio.
-- Baris lama (id = 1) tetap dipakai sebagai audio pertama. Hanya Super Admin yang menambah/mengubah/menghapus;
-- siapa pun boleh membaca. Jalankan SETELAH asma.sql. Aman dijalankan ulang.
-- ============================================================
alter table public.asma_audio_setting drop constraint if exists asma_audio_setting_id_check;

do $$
begin
  if not exists (select 1 from pg_attribute where attrelid = 'public.asma_audio_setting'::regclass and attname = 'id' and attidentity <> '') then
    alter table public.asma_audio_setting alter column id add generated by default as identity;
  end if;
end $$;
select setval(pg_get_serial_sequence('public.asma_audio_setting', 'id'), greatest((select coalesce(max(id), 1) from public.asma_audio_setting), 1));

create or replace function public.asma_audio_cap()
returns trigger language plpgsql set search_path = '' as $$
begin
  if (select count(*) from public.asma_audio_setting) >= 10 then
    raise exception 'maksimal 10 audio' using errcode = '22023';
  end if;
  return new;
end $$;
revoke all on function public.asma_audio_cap() from public, anon, authenticated;
drop trigger if exists asma_audio_cap_trg on public.asma_audio_setting;
create trigger asma_audio_cap_trg before insert on public.asma_audio_setting for each row execute function public.asma_audio_cap();
